import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { commandCatalog } from "../packages/contracts/src/index.ts";

const docPath = fileURLToPath(new URL("../docs/nani/command-catalog.md", import.meta.url));
const startMarker = "<!-- BEGIN GENERATED COMMAND CATALOG -->";
const endMarker = "<!-- END GENERATED COMMAND CATALOG -->";

export function renderCommandCatalogBlock() {
  const official = commandCatalog.filter((definition) => definition.source === "naninovel");
  const project = commandCatalog.filter((definition) => definition.source === "v-ronpa");
  return [
    startMarker,
    "<!-- Generated by scripts/generate-command-catalog-doc.mjs. Do not edit this block by hand. -->",
    "### Official Naninovel declarations",
    "",
    renderTable(official),
    "",
    "### V-Ronpa project declarations",
    "",
    renderTable(project),
    endMarker
  ].join("\n");
}

export function updateCommandCatalogDoc(source) {
  const block = renderCommandCatalogBlock();
  if (source.includes(startMarker) && source.includes(endMarker)) {
    return source.replace(
      new RegExp(`${escapeRegExp(startMarker)}[\\s\\S]*?${escapeRegExp(endMarker)}`, "u"),
      block
    );
  }
  const withMatrix = source.replace(
    /## Official Naninovel Commands[\s\S]*?(?=Shared shorthand:)/u,
    `## Command Matrix (generated)\n\n${block}\n\n`
  );
  return withMatrix.replace(
    /## V-Ronpa Project Commands[\s\S]*?(?=Compatibility params currently attached to official commands:)/u,
    [
      "## V-Ronpa Project Commands",
      "",
      "Project commands and aliases are included in the generated matrix above; their",
      "status and execution owner come directly from `commandCatalog`.",
      "",
      ""
    ].join("\n")
  );
}

function renderTable(definitions) {
  const rows = definitions
    .slice()
    .sort((left, right) => left.canonicalName.localeCompare(right.canonicalName))
    .map((definition) => [
      `\`${definition.canonicalName}\``,
      `\`${definition.id}\``,
      definition.category,
      definition.execution,
      definition.params.length > 0
        ? definition.params.map((param) => `${param.name}:${param.type}${param.source === "v-ronpa" ? " (V-Ronpa)" : ""}`).join(", ")
        : "none",
      definition.primaryParam ?? "none",
      definition.supportsChildren ? "yes" : "no",
      definition.status
    ]);
  return [
    "| Command | Runtime id | Category | Execution | Params | Primary | Children | Status |",
    "|---|---|---|---|---|---|---|---|",
    ...rows.map((row) => `| ${row.map(escapeTableCell).join(" | ")} |`)
  ].join("\n");
}

function escapeTableCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

const current = readFileSync(docPath, "utf8");
const next = updateCommandCatalogDoc(current);
if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("docs/nani/command-catalog.md is stale. Run pnpm generate:command-docs.");
    process.exit(1);
  }
  console.log("Nani command catalog documentation is fresh.");
} else {
  writeFileSync(docPath, next);
  console.log("Updated docs/nani/command-catalog.md from commandCatalog.");
}
