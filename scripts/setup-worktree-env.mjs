import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { basename, resolve } from "node:path";

const cwd = resolve(process.cwd());
const hash = createHash("sha1").update(cwd).digest("hex");
const offset = Number.parseInt(hash.slice(0, 4), 16) % 1000;
const port = 5173 + offset;
const stateDir = ".local-state";

mkdirSync(stateDir, { recursive: true });

const envPath = ".env.worktree";
const content = [
  `# Generated by scripts/setup-worktree-env.mjs`,
  `WORKTREE_NAME=${basename(cwd)}`,
  `PORT=${port}`,
  `VITE_DEV_PORT=${port}`,
  `LOCAL_STORAGE_DIR=${stateDir}/${basename(cwd)}`,
  ""
].join("\n");

if (!existsSync(envPath)) {
  writeFileSync(envPath, content);
  console.log(`Created ${envPath} with PORT=${port}`);
} else {
  console.log(`${envPath} already exists; leaving it unchanged.`);
}
