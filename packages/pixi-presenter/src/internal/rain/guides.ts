function clamp(value: number, min: number, max: number) {
  return Math.min(Math.max(value, min), max);
}

function mixValue(a: number, b: number, amount: number) {
  return a + (b - a) * amount;
}

function mixPoint(a: Vec2, b: Vec2, amount: number): Vec2 {
  return [mixValue(a[0], b[0], amount), mixValue(a[1], b[1], amount)];
}

function mixGuide(a: BezierGuide, b: BezierGuide, amount: number): BezierGuide {
  return {
    p0: mixPoint(a.p0, b.p0, amount),
    p1: mixPoint(a.p1, b.p1, amount),
    p2: mixPoint(a.p2, b.p2, amount),
    p3: mixPoint(a.p3, b.p3, amount),
  };
}

export function buildGuides(settings: RainSettings): BezierGuide[] {
  const wind = clamp(settings.wind, -1, 1);

  if (wind < 0) {
    return leftGuides.map((guide, index) => mixGuide(guide, naturalGuides[index]!, wind + 1));
  }

  return naturalGuides.map((guide, index) => mixGuide(guide, rightGuides[index]!, wind));
}

export function guidesToUniforms(guides: BezierGuide[]) {
  const values: Record<string, number[]> = {};

  guides.slice(0, guideCount).forEach((guide, index) => {
    values[`uGuideA${index}`] = [guide.p0[0], guide.p0[1], guide.p1[0], guide.p1[1]];
    values[`uGuideB${index}`] = [guide.p2[0], guide.p2[1], guide.p3[0], guide.p3[1]];
  });

  return values;
}
